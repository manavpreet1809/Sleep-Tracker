-- One row per night. A workspace is an anonymous, browser-held ID that keeps each visitor's
-- nights separate without accounts.
CREATE TABLE sleep_night (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id        UUID             NOT NULL,
    night_date          DATE             NOT NULL,
    quality             INTEGER          NOT NULL CHECK (quality BETWEEN 1 AND 10),
    bedtime             TIME             NOT NULL,
    wake_time           TIME             NOT NULL,
    sleep_hours         DOUBLE PRECISION NOT NULL CHECK (sleep_hours BETWEEN 0 AND 24),
    room_temperature_c  DOUBLE PRECISION,
    cardio_minutes      INTEGER,
    nap_minutes         INTEGER,
    screen_time_hours   DOUBLE PRECISION,
    mattress_age_months INTEGER,
    water_intake_ml     INTEGER,
    source              VARCHAR(16)      NOT NULL DEFAULT 'manual',
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_sleep_night_workspace_date UNIQUE (workspace_id, night_date)
);
